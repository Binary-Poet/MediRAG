"""急症词表拦截（方案 4.4-2）：问题命中急症症状时强制就医引导。"""
import re

# 命中即拦截（含知识型提问，如「胸痛的病机」也会被拦截）——这是为保证医疗安全
# 而接受的可接受代价：宁可对知识型提问多引导一次就医，也不漏放真实急症。
EMERGENCY_WORDS = [
    "胸痛", "胸口疼", "昏迷", "晕厥", "大出血", "休克", "孕妇出血",
    "孕妇腹痛", "呼吸困难", "咯血", "吐血", "便血", "黑便", "剧烈头痛",
    "突发瘫痪", "抽搐", "气道异物", "意识不清", "心梗", "中风", "误服",
]

# 「中风」同形不同义：《伤寒论》「太阳中风」是表虚证候名（桂枝汤主治），现代「中风」是脑卒中。
# 纯子串匹配会把证候名判成急症——实测「麻黄汤和桂枝汤有什么区别」因反思轮补出「太阳中风证」
# 实体而弹出 120 急症横幅。故先消掉中医证候用法的「中风」，再做急症匹配。
_TCM_ZHONGFENG = re.compile(r"(太阳|阳明|少阳|太阴|少阴|厥阴)中风|中风(证|表虚)")


def detect_emergency(text: str) -> bool:
    """任意急症词命中即返回 True；中医证候名里的「中风」（太阳中风/中风证）不算。"""
    return any(w in _TCM_ZHONGFENG.sub("", text) for w in EMERGENCY_WORDS)
